/** Plural forms keyed by Intl.PluralRules category (Russian needs one/few/many). */
export type PluralForms = Partial<Record<Exclude<Intl.LDMLPluralRule, "other">, string>> & { other: string };

type Widen<T> = T extends string
  ? string
  : T extends { other: string }
    ? [Exclude<keyof T, Intl.LDMLPluralRule>] extends [never]
      ? PluralForms
      : { [K in keyof T]: Widen<T[K]> }
    : { [K in keyof T]: Widen<T[K]> };
export type Dictionary = Widen<typeof en>;
